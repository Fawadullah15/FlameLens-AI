"""
FlameLens AI — Research Reports Router
Generates publication-ready, evidence-based Markdown research reports
with full NASA provenance, measurement parameter sheets, and risk audits.
"""
from __future__ import annotations
import sys
sys.path.insert(0, "E:/pip-libs")
sys.path.insert(0, "E:/Flamelense/backend")

import uuid
from datetime import datetime
from fastapi import APIRouter, HTTPException
from fastapi.responses import PlainTextResponse
from typing import List, Dict, Any, Optional
from pydantic import BaseModel
from models.database import get_connection

router = APIRouter(prefix="/reports", tags=["Research Reports"])


class ReportRequest(BaseModel):
    experiment_ids: List[str]
    report_title: Optional[str] = None
    include_risk_breakdown: bool = True
    include_sensor_telemetry: bool = True
    include_citations: bool = True


@router.post("/generate", response_model=Dict[str, Any])
def generate_scientific_report(req: ReportRequest):
    """Generates comprehensive Markdown research report from verified flight records."""
    conn = get_connection()
    placeholders = ",".join(["?"] * len(req.experiment_ids))
    rows = conn.execute(f"""
        SELECT 
            e.*,
            m.burning_rate_constant_k,
            m.peak_flame_temperature_k,
            m.flame_standoff_ratio,
            m.flame_shape,
            m.soot_volume_fraction_ppm,
            m.soot_yield_category,
            m.limiting_oxygen_index_percent,
            m.burn_duration_seconds,
            m.extinction_mode,
            m.cool_flame_observed,
            m.measurement_uncertainty_percent,
            a.risk_score,
            a.risk_level,
            a.flammability_score,
            a.thermal_severity_score,
            a.soot_hazard_score,
            a.suppression_resistance_score,
            a.confidence_level,
            a.methodology,
            a.provenance_audit_trail
        FROM experiments e
        LEFT JOIN measurements m ON e.experiment_id = m.experiment_id
        LEFT JOIN analysis_results a ON e.experiment_id = a.experiment_id
        WHERE e.experiment_id IN ({placeholders})
    """, req.experiment_ids).fetchall()
    conn.close()

    if not rows:
        raise HTTPException(status_code=404, detail="No matching experiments found for report generation.")

    experiments = [dict(r) for r in rows]
    report_id = f"REP-{uuid.uuid4().hex[:8].upper()}"
    title = req.report_title or f"FlameLens Scientific Intelligence Report — {len(experiments)} Experiment Runs"
    now_str = datetime.now().strftime("%Y-%m-%d %H:%M UTC")

    # Build professional scientific report
    md = []
    md.append(f"# {title}")
    md.append(f"**FlameLens AI | NASA Space Apps Challenge 2026: Flame in Freefall**")
    md.append(f"*Generated:* {now_str} | *Report ID:* `{report_id}`\n")
    md.append("> ⚠️ **Official Scientific Provenance Disclaimer:**")
    md.append("> All experimental measurements documented in this report originate from peer-reviewed NASA publications and official flight telemetry archives (FLEX, ACME, CFI, BASS, SoFIE) aboard the International Space Station (ISS) and NASA Glenn Research Center drop towers.")
    md.append("> Flammability and risk assessments are computed deterministically from empirical measurements — NOT generated by black-box generative models.\n")
    md.append("---\n")

    md.append("## 1. Executive Summary")
    md.append(f"This report evaluates **{len(experiments)}** combustion runs across varying gravity vectors, ambient oxidizer concentrations, and fuel chemistries.")
    avg_k = [e["burning_rate_constant_k"] for e in experiments if e.get("burning_rate_constant_k")]
    if avg_k:
        md.append(f"- **Mean Burning Rate K:** `{sum(avg_k)/len(avg_k):.2f} mm²/s`")
    cool_flames = sum(1 for e in experiments if e.get("cool_flame_observed") == 1)
    if cool_flames:
        md.append(f"- **Cool Flame Incidents:** `{cool_flames}` (Sub-750K low-temperature combustion bypassing optical detection)")
    md.append("\n---\n")

    md.append("## 2. Experimental Telemetry & Measurements")
    for exp in experiments:
        md.append(f"### Experiment Run: `{exp['experiment_id']}` — {exp['title']}")
        md.append(f"| Parameter | Specification | Provenance / Notes |")
        md.append(f"| :--- | :--- | :--- |")
        md.append(f"| **Series** | `{exp.get('series')}` | {exp.get('mission_platform')} |")
        md.append(f"| **Fuel Stream** | `{exp.get('fuel_type')}` ({exp.get('fuel_category')}) | Initial Size: {exp.get('initial_fuel_diameter_mm') or 'N/A'} mm |")
        md.append(f"| **Gravity Level** | `{exp.get('gravity_level')} g` | {'Pure Microgravity (diffusive)' if exp.get('gravity_level', 0) < 0.1 else 'Terrestrial Buoyant (1-g)'} |")
        md.append(f"| **Chamber Environment** | `{exp.get('ambient_o2_percent')}% O₂`, `{exp.get('chamber_pressure_kpa')} kPa` | Diluent: `{exp.get('diluent_gas')}` |")
        md.append(f"| **Burning Rate K** | `{exp.get('burning_rate_constant_k') or 'N/A'} mm²/s` | D² Law Regression Constant |")
        md.append(f"| **Peak Flame Temp** | `{exp.get('peak_flame_temperature_k') or 'N/A'} K` | Radiometric measurement |")
        md.append(f"| **Flame Geometry** | `{exp.get('flame_shape')}` | Standoff Ratio: `{exp.get('flame_standoff_ratio') or 'N/A'}` |")
        md.append(f"| **Soot Volume Fraction** | `{exp.get('soot_volume_fraction_ppm') or '0.0'} ppm` | Yield Category: `{exp.get('soot_yield_category')}` |")
        md.append(f"| **Extinction Mode** | `{exp.get('extinction_mode')}` | LOI: `{exp.get('limiting_oxygen_index_percent') or 'N/A'}%` |")
        md.append(f"| **Cool Flame Observed** | `{'YES (650K)' if exp.get('cool_flame_observed') else 'No'}` | {'Sustained low-temperature evaporation' if exp.get('cool_flame_observed') else 'Standard hot flame'} |")
        md.append(f"\n**Primary Flight Finding:**\n> {exp.get('key_finding')}\n")
        md.append(f"**Citation:** {exp.get('citation')} *(Page/Section: {exp.get('page_citation') or 'Flight Record'})*\n")

    if req.include_risk_breakdown:
        md.append("\n---\n")
        md.append("## 3. Fire-Safety Risk Ranking & Vulnerability Audit")
        md.append("| Experiment ID | Fuel | Risk Score | Risk Category | Confidence | Provenance |")
        md.append("| :--- | :--- | :--- | :--- | :--- | :--- |")
        for exp in experiments:
            md.append(f"| `{exp['experiment_id']}` | {exp['fuel_type']} | **{exp.get('risk_score', 0):.1f}/100** | `{exp.get('risk_level')}` | {exp.get('confidence_level')} | {exp.get('series')} Flight Data |")

    md.append("\n---\n")
    md.append("## 4. Spacecraft Mission Fire Safety Recommendations")
    md.append("1. **Cabin Ventilation Airflow Regulation:** Without convective draft, solid material flames self-extinguish; ventilation loops must include emergency automatic fan cutoffs.")
    md.append("2. **Dedicated Cool Flame Chemical Detection:** Deploy non-dispersive infrared (NDIR) sensors calibrated for formaldehyde (HCHO) and carbon monoxide (CO) to detect sub-750K cool combustion.")
    md.append("3. **Exploration Atmosphere Flammability Recalibration:** Re-test all materials scheduled for lunar / Mars transit under elevated oxygen (30-34% O₂) and reduced pressure (56 kPa).")
    md.append("\n---\n*NASA Space Apps 2026 — Flame in Freefall | FlameLens AI Autonomous Intelligence*")

    full_markdown = "\n".join(md)

    return {
        "report_id": report_id,
        "title": title,
        "generated_at": now_str,
        "experiment_count": len(experiments),
        "markdown_content": full_markdown
    }
